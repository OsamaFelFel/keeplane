"""Collect pinned source archives and packaging files without executing them."""

import argparse
import hashlib
import json
import re
import threading
import time
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path
from urllib.request import urlopen


class Budget:
    def __init__(self):
        self.deadline = time.monotonic() + 240
        self.bytes = 0
        self.lock = threading.Lock()

    def consume(self, size):
        with self.lock:
            self.bytes += size
            if self.bytes > 256 * 1024 * 1024 or time.monotonic() >= self.deadline:
                raise ValueError("Collection size or time limit exceeded")


def download(task, output, budget):
    origin, name, algorithm, digest, urls = task
    destination = output / origin / name
    destination.parent.mkdir(parents=True, exist_ok=True)
    partial = destination.with_name(name + ".partial")
    errors = []
    for url in urls:
        try:
            if time.monotonic() >= budget.deadline:
                raise ValueError("Collection time limit exceeded")
            checksum, size = hashlib.new(algorithm), 0
            with urlopen(url, timeout=15) as response, partial.open("wb") as file:
                while chunk := response.read(1024 * 1024):
                    size += len(chunk)
                    if size > 64 * 1024 * 1024:
                        raise ValueError("Source file exceeds 64 MiB")
                    budget.consume(len(chunk))
                    checksum.update(chunk)
                    file.write(chunk)
            if checksum.hexdigest() != digest:
                raise ValueError("Checksum mismatch")
            partial.replace(destination)
            return {
                "origin": origin,
                "name": name,
                "url": url,
                "bytes": size,
                "algorithm": algorithm,
                "digest": digest,
                "verified": True,
            }
        except (OSError, ValueError) as error:
            partial.unlink(missing_ok=True)
            errors.append(f"{url}: {error}")
    return {"origin": origin, "name": name, "verified": False, "errors": errors}


def source_tasks(recipe, data, release):
    """Only literal checksum records are supported; shell is never evaluated."""
    block = re.search(r'^sha512sums="(.*?)"', data, re.MULTILINE | re.DOTALL)
    if block is None:
        if recipe["origin"] == "alpine-base":
            return []  # Release metadata is generated by its retained APKBUILD.
        raise ValueError("Missing literal sha512sums table")
    tasks, seen = [], set()
    for line in block[1].splitlines():
        if not line.strip():
            continue
        record = re.fullmatch(
            r"([a-f0-9]{128})\s+([A-Za-z0-9_][A-Za-z0-9@+._-]*)", line.strip()
        )
        if not record:
            raise ValueError("Unsupported checksum record")
        digest, name = record.groups()
        if name == "APKBUILD" or name.endswith(".partial"):
            raise ValueError("Reserved source filename")
        if name in seen:
            raise ValueError("Duplicate checksum filename")
        seen.add(name)
        local = recipe["url"].rsplit("/", 1)[0] + "/" + name
        mirror = f"https://distfiles.alpinelinux.org/distfiles/{release}/{name}"
        archive = bool(re.search(r"\.(?:tar\.(?:gz|bz2|xz|zst)|tgz|zip)$", name))
        tasks.append(
            (
                recipe["origin"],
                name,
                "sha512",
                digest,
                [mirror, local] if archive else [local, mirror],
            )
        )
    if not tasks:
        raise ValueError("Empty checksum table")
    return tasks


def collect(pins, output):
    release = pins["alpine_release"]
    if not re.fullmatch(r"v[0-9]+\.[0-9]+", release):
        raise ValueError("Invalid Alpine release")
    origins = [recipe["origin"] for recipe in pins["recipes"]]
    if len(set(origins)) != len(origins) or "python" in origins:
        raise ValueError("Duplicate or reserved recipe origin")
    for recipe in pins["recipes"]:
        if not re.fullmatch(
            r"[A-Za-z0-9][A-Za-z0-9+_.-]*", recipe["origin"]
        ) or not re.fullmatch(
            r"https://raw\.githubusercontent\.com/alpinelinux/aports/[a-f0-9]{40}/"
            + r"(?:main|community)/"
            + re.escape(recipe["origin"])
            + r"/APKBUILD",
            recipe["url"],
        ):
            raise ValueError("Invalid pinned recipe")
    if not re.fullmatch(r"[0-9]+\.[0-9]+\.[0-9]+", pins["python"]["version"]):
        raise ValueError("Invalid Python version")
    output.mkdir(parents=True, exist_ok=False)
    budget, results = Budget(), []
    python = pins["python"]
    tasks = [
        (r["origin"], "APKBUILD", "sha256", r["sha256"], [r["url"]])
        for r in pins["recipes"]
    ]
    tasks.append(
        (
            "python",
            "Dockerfile",
            "sha256",
            python["dockerfile_sha256"],
            [python["dockerfile_url"]],
        )
    )
    tasks.append(
        (
            "python",
            "Dockerfile.LICENSE",
            "sha256",
            python["dockerfile_license_sha256"],
            [python["dockerfile_license_url"]],
        )
    )
    with ThreadPoolExecutor(max_workers=3) as pool:
        results.extend(pool.map(lambda task: download(task, output, budget), tasks))
        if all(result["verified"] for result in results):
            try:
                tasks = []
                for recipe in pins["recipes"]:
                    tasks.extend(
                        source_tasks(
                            recipe,
                            (output / recipe["origin"] / "APKBUILD").read_text(),
                            release,
                        )
                    )
                tasks.append(
                    (
                        "python",
                        f"Python-{python['version']}.tar.xz",
                        "sha256",
                        python["source_sha256"],
                        [python["source_url"]],
                    )
                )
                results.extend(
                    pool.map(lambda task: download(task, output, budget), tasks)
                )
            except (OSError, ValueError) as error:
                results.append({"verified": False, "error": str(error)})
    report = {
        "base_image": pins["base_image"],
        "artifacts": results,
        "transferred_bytes": budget.bytes,
        "recipes_executed": False,
        "archives_extracted": False,
        "complete_licensing_inventory": False,
    }
    (output / "collection.json").write_text(json.dumps(report, indent=2) + "\n")
    return report


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--output", type=Path, required=True, help="Fresh directory outside Git"
    )
    args = parser.parse_args()
    try:
        pins = json.loads(
            (Path(__file__).parent / "licenses/runtime-sources.json").read_text()
        )
        report = collect(pins, args.output)
    except (OSError, ValueError, KeyError) as error:
        parser.exit(1, f"Source collection failed: {error}\n")
    passed = all(result["verified"] for result in report["artifacts"])
    print(
        json.dumps(
            {
                "verified": sum(r["verified"] for r in report["artifacts"]),
                "complete_licensing_inventory": False,
                "successful": passed,
            }
        )
    )
    return 0 if passed else 1


if __name__ == "__main__":
    raise SystemExit(main())
