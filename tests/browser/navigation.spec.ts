import { expect, test } from '@playwright/test'
import { firstAdminPassword } from './credentials'

test('NAV-01 ACCT-11: sign-in has no registration flow and pages share one React application', async ({ page }) => {
  await page.goto('/sign-in')
  await expect(page.getByLabel('Username')).toBeVisible()
  await expect(page.getByLabel('Password', { exact: true })).toBeVisible()
  await expect(page.getByRole('link', { name: /create an account|sign up/i })).toHaveCount(0)
  await expect(page.getByRole('link', { name: /single sign-on/i })).toHaveCount(0)
  await page.getByLabel('Username').fill('first-admin')
  await page.getByLabel('Password', { exact: true }).fill(firstAdminPassword())
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Users', exact: true })).toBeVisible()
  await page.evaluate(() => { document.documentElement.dataset.navigationProof = 'same-document' })
  await page.getByRole('link', { name: 'Models and routing', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Models and routing', exact: true })).toBeVisible()
  await expect(page.locator('html')).toHaveAttribute('data-navigation-proof', 'same-document')
  await page.getByRole('link', { name: 'Data classes', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Data classes', exact: true })).toBeVisible()
  await page.getByRole('link', { name: 'Audit', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Audit', exact: true })).toBeVisible()
  await page.setViewportSize({ width: 320, height: 800 })
  await page.getByRole('button', { name: 'Menu', exact: true }).click()
  await page.getByRole('link', { name: 'Users', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Users', exact: true })).toBeVisible()
  await expect(page.getByRole('dialog')).not.toBeVisible()
  await page.getByRole('button', { name: 'Sign out', exact: true }).click()
  await expect(page.getByLabel('Password', { exact: true })).toBeVisible()
})

test('NAV-02 ACCT-09: Editions renders in React and its note setting persists', async ({ page }) => {
  await page.goto('/sign-in')
  await page.getByLabel('Username').fill('first-admin')
  await page.getByLabel('Password', { exact: true }).fill(firstAdminPassword())
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Users', exact: true })).toBeVisible()
  await page.getByRole('link', { name: 'Editions', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Open Source includes' })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Enterprise adds' })).toBeVisible()
  const control = page.getByRole('switch', { name: 'Show a note where a feature is part of Enterprise' })
  await expect(control).toBeEnabled()
  const initial = await control.isChecked()
  try {
    await control.setChecked(!initial)
    await expect(page.getByRole('status')).toHaveText(initial ? 'The note is off.' : 'The note is on.')
    await page.reload()
    await expect(control).toBeEnabled()
    await expect(control).toBeChecked({ checked: !initial })
  } finally {
    await control.setChecked(initial)
    await expect(control).toBeEnabled()
    await page.getByRole('button', { name: 'Sign out', exact: true }).click()
  }
})
